// Builds src/fonts.css with only the Shippori Mincho slices that contain the CJK characters the game
// actually uses (instead of shipping ~120 Japanese slices). Re-run after adding new kanji to the UI.
import fs from 'node:fs'; import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
const used = new Set();
for (const f of walk(path.join(root, 'src')).filter((f) => /\.(tsx?|css)$/.test(f) && !f.endsWith('fonts.css')))
  for (const ch of fs.readFileSync(f, 'utf8')) if (ch.codePointAt(0) > 0x2e80) used.add(ch.codePointAt(0));
const inRange = (cp, range) => range.split(',').some((r) => {
  const m = r.trim().replace('U+', '').split('-'); const a = parseInt(m[0], 16), b = m[1] ? parseInt(m[1], 16) : a; return cp >= a && cp <= b; });
let out = `/* generated by scripts/gen-fonts.mjs — characters: ${[...used].map((c) => String.fromCodePoint(c)).join('')} */\n`;
for (const w of [800]) {
  const css = fs.readFileSync(path.join(root, `node_modules/@fontsource/shippori-mincho/${w}.css`), 'utf8');
  const blocks = css.split('@font-face').slice(1).map((b) => '@font-face' + b.slice(0, b.indexOf('}') + 1));
  const keep = blocks.filter((b) => { const r = /unicode-range:\s*([^;]+);/.exec(b); return r && [...used].some((cp) => inRange(cp, r[1])); });
  out += keep.map((b) => b.replace(/url\(\.\/files\//g, 'url(../node_modules/@fontsource/shippori-mincho/files/').replace(/,\s*url\([^)]*\.woff\) format\('woff'\)/, '')).join('\n') + '\n';
  console.log(`weight ${w}: ${keep.length} of ${blocks.length} slices`);
}
fs.writeFileSync(path.join(root, 'src/fonts.css'), out);
